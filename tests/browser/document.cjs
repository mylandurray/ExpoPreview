const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || undefined, headless: true, args: ['--no-sandbox', '--use-gl=angle', '--use-angle=swiftshader'] });
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
 const errors=[]; page.on('pageerror', e => errors.push(e.message));
 await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5173');
 await page.waitForFunction(() => window.__store);
 await page.evaluate(() => __store.getState().setProject({ name: 'Keep these notes' }));
 const chooser = page.waitForEvent('filechooser');
 await page.getByRole('button', { name: 'File', exact: true }).click();
 await page.getByRole('menuitem', { name: /Open/ }).click();
 await (await chooser).setFiles({ name: 'replacement.exposcene', mimeType: 'application/json', buffer: Buffer.from('{"version":2,"project":{"name":"Replacement"}}') });
 await page.getByRole('dialog').waitFor();
 assert.equal(await page.evaluate(() => __store.getState().doc.project.name), 'Keep these notes');
 await page.getByRole('button', { name: 'Cancel', exact: true }).click();
 assert.equal(await page.evaluate(() => __store.getState().doc.project.name), 'Keep these notes');
 await page.getByRole('button', { name: 'File', exact: true }).click();
 await page.getByRole('menuitem', { name: 'New layout', exact: true }).click();
 await page.getByRole('dialog').waitFor();
 await page.getByRole('button', { name: 'Discard', exact: true }).click();
 await page.waitForFunction(() => __store.getState().doc.project.name === 'Untitled stand');
 await page.getByRole('button', { name: 'File', exact: true }).click();
 await page.getByRole('menuitem', { name: 'Recover previous layout' }).click();
 await page.waitForFunction(() => __store.getState().doc.project.name === 'Keep these notes');
 await page.evaluate(async () => { const { openSceneFile } = await import('/src/state/actions.js'); await openSceneFile(new File(['{"version":2,"stand":{"type":"bogus"}}'], 'invalid.exposcene')); });
 assert.equal(await page.evaluate(() => __store.getState().doc.project.name), 'Keep these notes');
 assert.equal(await page.getByRole('dialog').count(), 0);
 // Shortcut Open and Save download use the same replacement workflow.
 await page.evaluate(() => __store.getState().setProject({ notes: 'Unsaved shortcut changes' }));
 const shortcutChooser = page.waitForEvent('filechooser');
 await page.keyboard.press('Control+o');
 await (await shortcutChooser).setFiles({ name: 'shortcut.exposcene', mimeType: 'application/json', buffer: Buffer.from('{"version":2,"project":{"name":"Shortcut"}}') });
 const download = page.waitForEvent('download');
 await page.getByRole('button', { name: 'Save and replace', exact: true }).click();
 await download;
 await page.waitForFunction(() => __store.getState().doc.project.name === 'Shortcut');
 await page.evaluate(() => __store.getState().setProject({ notes: 'Protect drop' }));
 await page.locator('.viewport').evaluate((el) => {
   const transfer = new DataTransfer();
   transfer.items.add(new File(['{"version":2,"project":{"name":"Drop"}}'], 'drop.exposcene', { type: 'application/json' }));
   el.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: transfer }));
 });
 await page.getByRole('dialog').waitFor();
 await page.keyboard.press('Escape');
 await page.waitForFunction(() => !__store.getState().replacement);
 assert.equal(await page.evaluate(() => __store.getState().doc.project.name), 'Shortcut');
 assert.deepEqual(errors, []);
 console.log('PASS: menu and shortcut Open, Save/Discard/Cancel, drop/Escape, recovery, invalid-import protection; no page errors');
 await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
